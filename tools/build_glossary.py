"""Build the master glossary from every word source on the portal.

Usage (from the repo root):
    python3 tools/build_glossary.py

Reads every vocabulary-bearing data contract on the site and writes:
  - practice/glossary/glossary.json  (drives the Glossary page AND the Practice deck)
  - practice/glossary/glossary.xlsx  (the tagged spreadsheet: Tab, List, Arabic,
    Transliteration, English, Source page)

Each term carries: section (the portal tab), list (the word list it belongs to),
scope id (stable, used by Practice deep links), and the source page href.
Adding a new word source = add one loader below and rerun. Fails loudly on any
shape surprise. Requires: openpyxl.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

TERMS = []   # {section, list, scope, ar, tr, en, src}
LISTS = []   # ordered {scope, section, list, src} for the deck's pickers


def add_list(scope, section, name, src, words):
    """words: iterable of (ar, tr, en). Skips empty lists."""
    rows = [(a, t, e) for a, t, e in words if a and e]
    if len(rows) < 2:
        return
    LISTS.append({"scope": scope, "section": section, "list": name, "src": src})
    for ar, tr, en in rows:
        TERMS.append({"section": section, "list": name, "scope": scope,
                      "ar": ar, "tr": tr or "", "en": en, "src": src})


# --- Arabic levels -------------------------------------------------------
lv = json.load(open("arabic/vocab/levels.json", encoding="utf-8"))
for lk in sorted(lv):
    n = lk[-1]
    for mk in sorted(lv[lk], key=int):
        m = lv[lk][mk]
        if not isinstance(m, dict) or "words" not in m:
            continue
        add_list("lv:%s:%s" % (lk, mk), "Arabic · Level %s" % n,
                 "Month %s — %s" % (mk, m["topic"]), "arabic/vocab/",
                 ((w[0], w[1], w[2]) for w in m["words"]))

# --- Theme word banks ----------------------------------------------------
th = json.load(open("arabic/themes/themes.json", encoding="utf-8"))
for i, t in enumerate(th["themes"]):
    add_list("th:%d" % i, "Arabic · Themes", t["name"], "arabic/themes/",
             ((c.get("ar"), c.get("ar_ipa", ""), c.get("en")) for c in t["cards"]))

# --- Alphabet, numbers, harakat -----------------------------------------
letters = json.load(open("practice/deck/letters-extract.json", encoding="utf-8"))
add_list("al:1", "Arabic · Foundations", "The Alphabet (28 letters)",
         "arabic/letters/", ((x["ar"], x["tr"], x["en"]) for x in letters))

numbers = json.load(open("practice/deck/numbers-extract.json", encoding="utf-8"))
add_list("nu:1", "Arabic · Foundations", "Numbers 0–100",
         "arabic/numbers/", ((x["ar"], x["tr"], x["en"]) for x in numbers))

vw = json.load(open("arabic/vowels/vowels.json", encoding="utf-8"))
add_list("hk:1", "Arabic · Foundations", "Harakat & marks",
         "arabic/vowels/",
         (("ب" + v["mark"], v["suffix"], v["name"]) for v in vw["vowels"]))

# --- 80% Qur'anic Words --------------------------------------------------
cq = json.load(open("quran/concentration/data.json", encoding="utf-8"))
for i, p in enumerate(cq["pages"]):
    words = []
    for theme in p["themes"]:
        for e in theme["entries"]:
            words.append((e.get("ar"), e.get("tag", ""), e.get("en")))
    titles = " / ".join(t["title"] for t in p["themes"])
    add_list("cq:%d" % i, "Quran · 80% Words",
             "%s — %s" % (p["label"], titles), "quran/concentration/", words)

# --- Islamic Studies -----------------------------------------------------
im = json.load(open("islamic-studies/vocab/months.json", encoding="utf-8"))
for mk in sorted((k for k in im if k.isdigit()), key=int):
    m = im[mk]
    if not isinstance(m, dict) or "words" not in m:
        continue
    add_list("is:%s" % mk, "Islamic Studies · Hijri Year",
             "Month %s — %s: %s" % (mk, m.get("name", ""), m.get("theme", "")),
             "islamic-studies/vocab/",
             ((w[0], w[1], w[2]) for w in m["words"]))

names = json.load(open("practice/deck/names-extract.json", encoding="utf-8"))
add_list("n99:1", "Islamic Studies · Reference", "The 99 Names of Allah",
         "islamic-studies/names-of-allah/",
         ((x["ar"], x["tr"], x["en"]) for x in names))

# --- outputs -------------------------------------------------------------
out = {
    "note": ("MASTER GLOSSARY - generated by tools/build_glossary.py from every "
             "word source on the portal (levels, themes, alphabet, numbers, "
             "harakat, 80% words, hijri months, 99 Names). Do not hand-edit: "
             "fix the source contract and rerun the script. This file drives "
             "both the Glossary page and the Practice deck, so a new source "
             "added here appears in both automatically."),
    "built_from": sorted({t["src"] for t in TERMS}),
    "lists": LISTS,
    "terms": TERMS,
}
json.dump(out, open("practice/glossary/glossary.json", "w", encoding="utf-8"),
          ensure_ascii=False, indent=1)

import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.table import Table, TableStyleInfo

wb = openpyxl.Workbook()
ws = wb.active
ws.title = "Glossary"
ws["A1"] = "Al Baseera Academy - Master Glossary"
ws["A1"].font = Font(size=14, bold=True, color="FFFFFF")
ws["A1"].fill = PatternFill("solid", fgColor="1B2A5E")
ws["A1"].alignment = Alignment(horizontal="center", vertical="center")
ws.merge_cells("A1:F1")
ws.row_dimensions[1].height = 24
ws["A2"] = ("Every term on the portal, tagged by tab and word list. Generated "
            "by tools/build_glossary.py - regenerate after content changes.")
ws["A2"].font = Font(size=9, italic=True, color="55544A")
ws.merge_cells("A2:F2")

HDR = 4
heads = ["Tab", "Word list", "Arabic", "Transliteration", "English", "Source page"]
for c, head in enumerate(heads, start=1):
    cell = ws.cell(HDR, c, head)
    cell.font = Font(bold=True, color="FFFFFF")
    cell.fill = PatternFill("solid", fgColor="C9A13B")
for r, t in enumerate(TERMS, start=HDR + 1):
    ws.cell(r, 1, t["section"])
    ws.cell(r, 2, t["list"])
    a = ws.cell(r, 3, t["ar"])
    a.alignment = Alignment(horizontal="right", readingOrder=2)
    a.font = Font(size=13)
    ws.cell(r, 4, t["tr"])
    ws.cell(r, 5, t["en"])
    ws.cell(r, 6, t["src"])
last = HDR + len(TERMS)
tbl = Table(displayName="Glossary", ref="A%d:F%d" % (HDR, last))
tbl.tableStyleInfo = TableStyleInfo(name="TableStyleMedium2", showRowStripes=True)
ws.add_table(tbl)
for col, w in zip("ABCDEF", [24, 38, 18, 20, 34, 24]):
    ws.column_dimensions[col].width = w
ws.freeze_panes = "A%d" % (HDR + 1)
wb.save("practice/glossary/glossary.xlsx")

print("glossary: %d terms in %d lists across %d sections"
      % (len(TERMS), len(LISTS), len({t['section'] for t in TERMS})))
print("sections:", sorted({t["section"] for t in TERMS}))
